-- PostgreSQL/Supabase schema. Business dates remain DATE or local wall-clock TIMESTAMP
-- to preserve the original application semantics; session expiry is UTC.
CREATE TABLE IF NOT EXISTS clientes (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome varchar(120) NOT NULL, telefone varchar(30), email varchar(120),
 data_compra date NOT NULL, valor_orcamento numeric(12,2) NOT NULL DEFAULT 0,
 valor_vendido numeric(12,2) NOT NULL DEFAULT 0,
 status varchar(20) NOT NULL DEFAULT 'orcamento' CHECK (status IN ('orcamento','aprovado','em_andamento','entregue','cancelado')),
 forma_pagamento varchar(20) NOT NULL DEFAULT 'a_vista' CHECK (forma_pagamento IN ('a_vista','mensal','parcelas')),
 data_pagamento_vista date, valor_mensal numeric(12,2),
 dia_vencimento smallint CHECK (dia_vencimento BETWEEN 0 AND 255), data_inicio_mensalidade date,
 qtd_parcelas integer CHECK (qtd_parcelas >= 0), valor_parcela numeric(12,2),
 data_primeira_parcela date, parcelas_pagas integer DEFAULT 0 CHECK (parcelas_pagas >= 0),
 validade_orcamento date, data_aprovacao date, previsao_entrega date, data_entrega date,
 motivo_cancelamento varchar(255), dias_manutencao integer NOT NULL DEFAULT 90 CHECK (dias_manutencao >= 0),
 dias_renovacao integer NOT NULL DEFAULT 365 CHECK (dias_renovacao >= 0), observacoes text,
 documento_caminho varchar(255), documento_nome varchar(255), documento_tipo varchar(120),
 criado_em timestamp NOT NULL, atualizado_em timestamp NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_clientes_status ON clientes(status);
CREATE INDEX IF NOT EXISTS idx_clientes_data_compra ON clientes(data_compra);
CREATE INDEX IF NOT EXISTS idx_clientes_nome ON clientes(nome);
CREATE INDEX IF NOT EXISTS idx_clientes_forma_pagamento ON clientes(forma_pagamento);

CREATE TABLE IF NOT EXISTS usuarios (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome varchar(120) NOT NULL, email varchar(190) NOT NULL UNIQUE, senha_hash varchar(255),
 criado_em timestamp NOT NULL, atualizado_em timestamp NOT NULL, ultimo_acesso timestamp
);

