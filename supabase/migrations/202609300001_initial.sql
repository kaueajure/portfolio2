CREATE TABLE IF NOT EXISTS notas (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cliente_id integer REFERENCES clientes(id) ON DELETE SET NULL,
 titulo varchar(160) NOT NULL, conteudo text NOT NULL,
 criada_em timestamp NOT NULL, atualizada_em timestamp NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_notas_cliente ON notas(cliente_id);
CREATE INDEX IF NOT EXISTS idx_notas_atualizada ON notas(atualizada_em);

CREATE TABLE IF NOT EXISTS produtos_servicos (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome varchar(160) NOT NULL, tipo_preco varchar(10) NOT NULL DEFAULT 'fixo' CHECK (tipo_preco IN ('fixo','hora')),
 preco numeric(12,2) NOT NULL DEFAULT 0, descricao text,
 ativo boolean NOT NULL DEFAULT true, ordem integer NOT NULL DEFAULT 0,
 criado_em timestamp NOT NULL, atualizado_em timestamp NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_produtos_ativo_ordem ON produtos_servicos(ativo,ordem);

CREATE TABLE IF NOT EXISTS propostas (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo varchar(32) NOT NULL UNIQUE, token_publico char(64) NOT NULL UNIQUE,
 cliente_id integer REFERENCES clientes(id) ON DELETE SET NULL,
 titulo varchar(200) NOT NULL,
 status varchar(20) NOT NULL DEFAULT 'rascunho' CHECK (status IN ('rascunho','enviada','visualizada','aceita','recusada','expirada','cancelada')),
 validade date, desconto_valor numeric(12,2) NOT NULL DEFAULT 0,
 desconto_percentual numeric(5,2) NOT NULL DEFAULT 0,
 subtotal numeric(12,2) NOT NULL DEFAULT 0, total numeric(12,2) NOT NULL DEFAULT 0,
 condicoes text, escopo text, visualizada_em timestamp, respondida_em timestamp,
 resposta_cliente text, criada_em timestamp NOT NULL, atualizada_em timestamp NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_propostas_status ON propostas(status);
CREATE INDEX IF NOT EXISTS idx_propostas_cliente ON propostas(cliente_id);
CREATE INDEX IF NOT EXISTS idx_propostas_atualizada ON propostas(atualizada_em);

CREATE TABLE IF NOT EXISTS proposta_itens (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 proposta_id integer NOT NULL REFERENCES propostas(id) ON DELETE CASCADE,
 produto_id integer REFERENCES produtos_servicos(id) ON DELETE SET NULL,
 nome_snapshot varchar(160) NOT NULL, descricao_snapshot text,
 tipo_preco varchar(10) NOT NULL DEFAULT 'fixo' CHECK (tipo_preco IN ('fixo','hora')),
 preco_unitario numeric(12,2) NOT NULL DEFAULT 0, quantidade numeric(12,2) NOT NULL DEFAULT 1,
 total_linha numeric(12,2) NOT NULL DEFAULT 0, ordem integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_itens_proposta ON proposta_itens(proposta_id,ordem);

CREATE TABLE IF NOT EXISTS proposta_visualizacoes (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 proposta_id integer NOT NULL REFERENCES propostas(id) ON DELETE CASCADE,
 nome varchar(120) NOT NULL, visualizada_em timestamp NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_viz_proposta ON proposta_visualizacoes(proposta_id,visualizada_em);

CREATE TABLE IF NOT EXISTS app_sessions (
 token_hash char(64) PRIMARY KEY, user_id integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
 expires_at timestamp NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sessions_expiry ON app_sessions(expires_at);
CREATE TABLE IF NOT EXISTS app_rate_limits (
 bucket char(64) PRIMARY KEY, attempts integer NOT NULL CHECK (attempts >= 0), expires_at timestamp NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_rate_expiry ON app_rate_limits(expires_at);
CREATE TABLE IF NOT EXISTS app_proposal_sequences (
 year smallint PRIMARY KEY, number integer NOT NULL CHECK (number >= 0)
);

